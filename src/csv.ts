// Minimal RFC 4180 CSV parser (quoted fields, escaped quotes, newlines inside quotes).
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') inQuotes = false;
      else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => !(r.length === 1 && r[0] === ""));
}

import type { MatrixRow } from "./types.ts";

export function parseMatrix(text: string): MatrixRow[] {
  const [, ...rows] = parseCsv(text);
  return rows.map((r) => ({
    reqId: r[0],
    kind: r[1] as MatrixRow["kind"],
    artifact: r[2],
    locator: r[3],
    testId: r[4],
  }));
}
